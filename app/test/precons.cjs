// Screenshots the New game screen and a precon in the deck builder, then starts a game with a precon.
const { app, BrowserWindow } = require('electron');
const path = require('node:path');
const fs = require('node:fs');
const out = process.argv[process.argv.length - 1];
fs.mkdirSync(out, { recursive: true });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1440, height: 900, show: true });
  const errors = [];
  win.webContents.on('console-message', (_e, level, msg) => level >= 2 && errors.push(msg));
  await win.loadFile(path.join(__dirname, '..', 'dist', 'index.html'));
  const js = (c) => win.webContents.executeJavaScript(c);
  const shot = async (n) => { await sleep(300); fs.writeFileSync(path.join(out, `${n}.png`), (await win.capturePage()).toPNG()); };
  const click = (t) => js(`(() => { const b = [...document.querySelectorAll('button')].find(b => b.textContent.trim().startsWith(${JSON.stringify(t)}) && !b.disabled); if (b) { b.click(); return true; } return false; })()`);
  await click('Play vs bots');
  await sleep(300);
  console.log('decks listed:', await js(`[...document.querySelectorAll('.option .name')].slice(0, 8).map(e => e.textContent).join(', ')`));
  await click('Zombie Plague');
  await sleep(200);
  console.log('field after picking Zombie Plague:', await js(`[...document.querySelectorAll('.option[aria-pressed="true"] .name')].map(e => e.textContent).join(' + ')`));
  await click('Vampire Court');
  await sleep(200);
  console.log('field after picking Vampire Court:', await js(`[...document.querySelectorAll('.option[aria-pressed="true"] .name')].map(e => e.textContent).join(' + ')`));
  await shot('01-new-game');
  await click('Open deck builder');
  await sleep(300);
  await js(`(() => { const s = document.querySelector('header select'); const set = Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype, 'value').set; set.call(s, 'precon-construct'); s.dispatchEvent(new Event('change', { bubbles: true })); })()`);
  await sleep(300);
  console.log('builder count:', await js(`document.querySelector('.builder-deck span[style*="26px"]')?.textContent`));
  await shot('02-builder-construct');
  await js(`document.querySelector('[aria-label="Back to main menu"]').click()`);
  await sleep(200);
  await click('Play vs bots');
  await sleep(200);
  await click('Construct Foundry');
  await click('Start game');
  await sleep(500);
  for (let k = 0; k < 40 && !(await click('Keep')); k++) await sleep(150);
  for (let i = 0; i < 300 && !(await js(`document.body.innerText.includes('End Main phase')`)); i++) await sleep(100);
  console.log('opponents:', await js(`[...document.querySelectorAll('.opp-stats')].map(e => e.innerText.replace(/\\n/g, ' ')).join(' | ')`));
  await shot('03-game');
  console.log('console errors:', JSON.stringify(errors));
  app.quit();
});
